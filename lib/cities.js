export function getCityDisplayName(city, lang = 'az') {
  if (!city) return '';
  return city.nameByLang ? city.nameByLang[lang] || city.name : city.name;
}

export function findNearestCity(lat, lon, lang = 'az') {
  let nearest = WORLD_CITIES[0];
  let minDist = Infinity;
  for (const city of WORLD_CITIES) {
    const d = Math.hypot(city.lat - lat, city.lon - lon);
    if (d < minDist) {
      minDist = d;
      nearest = city;
    }
  }
  if (minDist < 1.2) {
    return getCityDisplayName(nearest, lang);
  }
  const prefix = lang === 'en' ? 'GPS Location' : lang === 'ru' ? 'GPS точка' : 'GPS Məkanı';
  return `${prefix} (${lat.toFixed(2)}, ${lon.toFixed(2)})`;
}
